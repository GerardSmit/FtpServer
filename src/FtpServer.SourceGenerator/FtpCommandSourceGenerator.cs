using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using FtpServer.SourceGenerator.Helpers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace FtpServer.SourceGenerator;

/// <summary>
/// Generates the command matcher and dispatcher for an enum marked with
/// <c>[GenerateCommandExtensions]</c>.
/// </summary>
/// <remarks>
/// Not a general-purpose dispatch generator despite taking any marked enum: the output names
/// FtpSession, FtpCommandHandler and the rest of this server's types, so an enum outside that
/// shape produces code that does not compile.
/// </remarks>
[Generator]
public class FtpCommandSourceGenerator : IIncrementalGenerator
{
    private const string GeneratorAttributeName = "FtpServer.GenerateCommandExtensionsAttribute";
    private const string FtpCommandAttributeName = "FtpServer.FtpCommandAttribute";

    private static readonly DiagnosticDescriptor EmptyCode = new(
        "FTPGEN001",
        "FTP command code must not be empty",
        "Enum member '{0}' has an empty [FtpCommand] code",
        "FtpServer",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor InvalidCode = new(
        "FTPGEN002",
        "FTP command code must be upper-case ASCII",
        "Enum member '{0}' has the [FtpCommand] code '{1}'; codes must consist of upper-case ASCII letters and digits",
        "FtpServer",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor DuplicateCode = new(
        "FTPGEN003",
        "Duplicate FTP command code",
        "Enum members '{0}' and '{1}' both declare the [FtpCommand] code '{2}'",
        "FtpServer",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<EnumInfo> declarations = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                GeneratorAttributeName,
                predicate: static (s, _) => s is EnumDeclarationSyntax,
                transform: static (ctx, _) => GetEnum(ctx, (EnumDeclarationSyntax)ctx.TargetNode))
            .Where(static e => e is not null)!;

        context.RegisterSourceOutput(declarations, Generate);
    }

    private static void Generate(SourceProductionContext ctx, EnumInfo info)
    {
        if (!Validate(ctx, info))
        {
            return;
        }

        var sb = new IndentedStringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        // Emitted into the enum's own namespace so the generator works in a consumer assembly,
        // not only in FtpServer.Core.
        var targetNamespace = string.IsNullOrEmpty(info.Namespace) ? null : info.Namespace;

        sb.AppendLine("using System;");
        sb.AppendLine("using System.Buffers;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine();

        if (targetNamespace is not null)
        {
            sb.AppendLine($"namespace {targetNamespace};");
            sb.AppendLine();
        }

        var maxLength = info.Values.Max(static v => v.Code.Length);
        var minLength = info.Values.Min(static v => v.Code.Length);

        using (sb.CodeBlock("public static class FtpCommandExtensions"))
        {
            using (sb.CodeBlock("public static string ToCommand(this FtpCommand name)"))
            {
                using (sb.CodeBlock("return name switch", close: "};"))
                {
                    foreach (var value in info.Values)
                    {
                        sb.AppendLine($"FtpCommand.{value.Name} => \"{value.Code}\",");
                    }

                    sb.AppendLine("_ => \"UNKNOWN\"");
                }
            }

            sb.AppendLine();

            sb.AppendLine("/// <summary>");
            sb.AppendLine("/// Matches a command verb. RFC 959 section 5.3.1 makes verbs case-insensitive, so the");
            sb.AppendLine("/// verb is upper-cased into a fixed-size stack buffer before matching.");
            sb.AppendLine("/// </summary>");

            using (sb.CodeBlock("public static FtpCommand FromUtf8(ReadOnlySpan<byte> span)"))
            {
                using (sb.CodeBlock($"if (span.Length < {minLength} || span.Length > {maxLength})"))
                {
                    sb.AppendLine("return FtpCommand.Unknown;");
                }

                sb.AppendLine();
                sb.AppendLine($"Span<byte> buffer = stackalloc byte[{maxLength}];");
                sb.AppendLine();

                using (sb.CodeBlock("for (var i = 0; i < span.Length; i++)"))
                {
                    sb.AppendLine("var b = span[i];");
                    sb.AppendLine("buffer[i] = (byte)(b >= (byte)'a' && b <= (byte)'z' ? b - 32 : b);");
                }

                sb.AppendLine();

                // A distinct local rather than reassigning the parameter: the parameter has a
                // wider escape scope than the stackalloc, which the ref-safety rules reject.
                sb.AppendLine("ReadOnlySpan<byte> verb = buffer.Slice(0, span.Length);");
                sb.AppendLine();

                var lengths = info.Values.GroupBy(static v => v.Code.Length);

                foreach (var lengthGroups in lengths)
                {
                    var groups = lengthGroups
                        .GroupBy(static v => v.Code[0])
                        .ToList();

                    using (sb.CodeBlock($"if (verb.Length == {lengthGroups.Key})"))
                    {
                        foreach (var charGroups in groups)
                        {
                            using (sb.CodeBlock($"if (verb[0] == '{charGroups.Key}')"))
                            {
                                foreach (var value in charGroups)
                                {
                                    sb.AppendLine($"if (verb.SequenceEqual(\"{value.Code}\"u8))");
                                    sb.AppendLine("{");
                                    sb.AppendLine($"    return FtpCommand.{value.Name};");
                                    sb.AppendLine("}");
                                    sb.AppendLine();
                                }

                                sb.AppendLine("return FtpCommand.Unknown;");
                            }

                            sb.AppendLine();
                        }

                        sb.AppendLine("return FtpCommand.Unknown;");
                    }

                    sb.AppendLine();
                }

                sb.AppendLine("return FtpCommand.Unknown;");
            }
        }

        sb.AppendLine();

        using (sb.CodeBlock("public abstract class FtpCommandHandler"))
        {
            sb.AppendLine("protected virtual ValueTask UnknownAsync(FtpSession session, FtpCommand command, ReadOnlySequence<byte> data, CancellationToken token) => throw new NotImplementedException();");
            sb.AppendLine();

            foreach (var value in info.Values)
            {
                sb.AppendLine($"public virtual ValueTask {value.Name}Async(FtpSession session, ReadOnlySequence<byte> data, CancellationToken token) => UnknownAsync(session, FtpCommand.{value.Name}, data, token);");
                sb.AppendLine();
            }

            using (sb.CodeBlock("public ValueTask HandleAsync(FtpSession session, FtpCommand command, ReadOnlySequence<byte> data, CancellationToken token)"))
            {
                using (sb.CodeBlock("return command switch", close: "};"))
                {
                    foreach (var value in info.Values)
                    {
                        sb.AppendLine($"FtpCommand.{value.Name} => {value.Name}Async(session, data, token),");
                    }

                    sb.AppendLine("_ => UnknownAsync(session, command, data, token)");
                }
            }
        }

        // Namespace-qualified: two enums may share a name, and a hint name collision fails the
        // compilation with nothing to point at.
        var hintName = string.IsNullOrEmpty(info.Namespace)
            ? $"{info.Name}.FtpCommandExtensions.g.cs"
            : $"{info.Namespace}.{info.Name}.FtpCommandExtensions.g.cs";

        ctx.AddSource(hintName, sb.ToString());
    }

    private static bool Validate(SourceProductionContext ctx, EnumInfo info)
    {
        var valid = true;
        var seen = new Dictionary<string, string>();

        foreach (var value in info.Values)
        {
            if (value.Code.Length == 0)
            {
                ctx.ReportDiagnostic(Diagnostic.Create(EmptyCode, Location.None, value.Name));
                valid = false;
                continue;
            }

            foreach (var c in value.Code)
            {
                if (c is (>= 'A' and <= 'Z') or (>= '0' and <= '9'))
                {
                    continue;
                }

                ctx.ReportDiagnostic(Diagnostic.Create(InvalidCode, Location.None, value.Name, value.Code));
                valid = false;
                break;
            }

            if (seen.TryGetValue(value.Code, out var previous))
            {
                ctx.ReportDiagnostic(Diagnostic.Create(DuplicateCode, Location.None, previous, value.Name, value.Code));
                valid = false;
            }
            else
            {
                seen[value.Code] = value.Name;
            }
        }

        return valid;
    }

    private static EnumInfo? GetEnum(GeneratorAttributeSyntaxContext ctx, EnumDeclarationSyntax enumDeclarationSyntax)
    {
        var attribute = ctx.SemanticModel.Compilation.GetTypeByMetadataName(FtpCommandAttributeName);
        if (attribute is null)
        {
            return null;
        }

        var symbol = ctx.SemanticModel.GetDeclaredSymbol(enumDeclarationSyntax) as INamedTypeSymbol;

        if (symbol is null)
        {
            return null;
        }

        var builder = ImmutableArray.CreateBuilder<EnumValueInfo>();

        foreach (var member in symbol.GetMembers())
        {
            if (member is not IFieldSymbol fieldSymbol)
            {
                continue;
            }

            var attributeData = fieldSymbol.GetAttribute(attribute);

            if (attributeData is null || attributeData.ConstructorArguments.Length == 0)
            {
                continue;
            }

            if (attributeData.ConstructorArguments[0].Value is not string code)
            {
                continue;
            }

            builder.Add(new EnumValueInfo(member.Name, code));
        }

        if (builder.Count == 0)
        {
            return null;
        }

        var symbolDisplayFormat = new SymbolDisplayFormat(typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces);
        var enumNamespace = symbol.ContainingNamespace.ToDisplayString(symbolDisplayFormat);

        return new EnumInfo(symbol.Name, enumNamespace, builder.ToImmutable());
    }
}

internal record EnumInfo(string Name, string? Namespace, EquatableArray<EnumValueInfo> Values);

// Deliberately holds no Location: this model is the incremental generator's cache key, and a
// Location changes on every unrelated edit to the file, defeating caching.
internal record EnumValueInfo(string Name, string Code);
